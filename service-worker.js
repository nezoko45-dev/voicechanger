const OFFSCREEN_URL = "offscreen.html";
let creatingOffscreen = null;
async function ensureOffscreen() {
  const contexts = await chrome.runtime.getContexts({contextTypes:["OFFSCREEN_DOCUMENT"],documentUrls:[chrome.runtime.getURL(OFFSCREEN_URL)]});
  if (contexts.length) return;
  if (creatingOffscreen) return creatingOffscreen;
  creatingOffscreen = chrome.offscreen.createDocument({url:OFFSCREEN_URL,reasons:["USER_MEDIA"],justification:"Keep microphone speech recognition running while the user switches from Chrome to a full-screen game."});
  try { await creatingOffscreen; } finally { creatingOffscreen = null; }
}
async function sendToElevenLabs(type, text) {
  const tabs = await chrome.tabs.query({url:["https://elevenlabs.io/*","https://*.elevenlabs.io/*"]});
  const tab = tabs.find(tab => tab.active) || tabs[0];
  if (!tab?.id) return {ok:false,message:"No ElevenLabs tab found. Open the Text to Speech page and refresh it."};
  try { return await chrome.tabs.sendMessage(tab.id,{type,text}); }
  catch (error) { return {ok:false,message:"Cannot reach the ElevenLabs tab. Open the Text to Speech page and refresh it so the extension can connect."}; }
}
function bytesToBase64(buffer) {
  const bytes = new Uint8Array(buffer);
  let binary = "";
  const chunkSize = 0x8000;
  for (let i = 0; i < bytes.length; i += chunkSize) {
    binary += String.fromCharCode(...bytes.subarray(i, i + chunkSize));
  }
  return btoa(binary);
}
async function generateWithApi(text) {
  const settings = await chrome.storage.local.get(["elevenLabsApiKey","voiceId","modelId"]);
  const apiKey = String(settings.elevenLabsApiKey || "").trim();
  const voiceId = String(settings.voiceId || "").trim();
  const modelId = String(settings.modelId || "eleven_flash_v2_5");
  if (!apiKey || !voiceId) return {ok:false,message:"Direct API is enabled but API key or voice ID is missing. Open the dashboard and save API settings."};
  const response = await fetch("https://api.elevenlabs.io/v1/text-to-speech/" + encodeURIComponent(voiceId) + "?output_format=mp3_44100_128", {
    method:"POST",
    headers:{"xi-api-key":apiKey,"Content-Type":"application/json","Accept":"audio/mpeg"},
    body:JSON.stringify({text,model_id:modelId})
  });
  if (!response.ok) {
    const detail = (await response.text()).slice(0,500);
    if (response.status === 401 || response.status === 403) return {ok:false,message:"ElevenLabs API authentication/permission failed. Check your API key and TTS permissions."};
    if (response.status === 429) return {ok:false,message:"ElevenLabs API rate or quota limit reached. Check your account usage."};
    return {ok:false,message:"ElevenLabs API returned HTTP " + response.status + (detail ? ": " + detail : "")};
  }
  const audioBase64 = bytesToBase64(await response.arrayBuffer());
  try {
    await chrome.runtime.sendMessage({type:"IVD_API_AUDIO",audioBase64,mimeType:"audio/mpeg"});
    return {ok:true,message:"Speech generated by the ElevenLabs API."};
  } catch (error) {
    return {ok:false,message:"Speech generated, but the dashboard could not play it. Keep dashboard.html open and click it once to allow audio playback."};
  }
}
chrome.runtime.onMessage.addListener((message,sender,sendResponse)=>{
  if(message?.type==="IVD_TOGGLE_LISTENING"){
    (async()=>{try{await ensureOffscreen();const result=await chrome.runtime.sendMessage({type:"IVD_OFFSCREEN_TOGGLE"});sendResponse(result||{listening:false,message:"Dictation engine did not respond. Reload the extension."});}
    catch(error){sendResponse({listening:false,message:"Could not start background dictation: "+(error?.message||error)});}})();
    return true;
  }
  if(message?.type==="IVD_BRIDGE_TO_ELEVENLABS"){
    (async()=>{
      try {
        const settings = await chrome.storage.local.get(["useDirectApi"]);
        if (settings.useDirectApi) {
          if (message.action === "preview") { sendResponse({ok:true,message:"Transcript captured for direct API generation."}); return; }
          sendResponse(await generateWithApi(String(message.text || ""))); return;
        }
        sendResponse(await sendToElevenLabs(message.action==="generate"?"IVD_GENERATE":"IVD_PREVIEW",message.text));
      } catch(error) { sendResponse({ok:false,message:error?.message||String(error)}); }
    })();
    return true;
  }
});